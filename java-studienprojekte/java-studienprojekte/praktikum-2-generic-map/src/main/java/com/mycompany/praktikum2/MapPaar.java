package com.mycompany.praktikum2;

import java.util.Map;


/**
 *
 * @author lewis
 * @param <K>
 * @param <V>
 */
public class MapPaar<K,V> implements Map.Entry<K,V> {

    final K key;
    V value;
    public MapPaar(K key, V value){
        this.key = key;
        this.value = value;
    }

    @Override
    public K getKey() {
        return key;
    }

    @Override
    public V getValue() {
        return value;
    }

    @Override
    public V setValue(V value) {
        V old = this.value;
        this.value = value;
        return old;
    }
}
